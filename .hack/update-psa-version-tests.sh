#!/usr/bin/env bash

# Regenerates the tests under pod-security-vpol/.psa-version-tests.
#
# The version-aware Pod Security Standards policies take the Pod Security Admission version
# from their psaMinor variable, and kyverno test can't override a variable. So each
# v1-<minor> test directory gets a copy of those policies with psaMinor set to that minor
# version. The v1-<default> directory tests the policy files themselves. Each directory's
# expected results come from upstream Pod Security Admission, through
# .hack/psa-expected-results, which needs Go. CI runs this script and fails if the output
# differs from the committed files.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PSS="${ROOT}/pod-security-vpol"
TESTS="${PSS}/.psa-version-tests"

POLICIES=(
  baseline/disallow-host-probes
  baseline/disallow-proc-mount
  baseline/disallow-selinux
  baseline/restrict-sysctls
  restricted/disallow-proc-mount-strict
  restricted/require-run-as-non-root-user
  restricted/require-run-as-nonroot
)

# The PSA minor versions where a version-aware policy changes, below the default.
VERSIONS=(25 27 29 31 32 34 35)

# default_minor prints the psaMinor default of a policy. It fails unless the policy sets
# psaMinor exactly once, as its first variable, so a patch of /spec/variables/0 sets it.
default_minor() {
  local values first
  values="$(awk 'prev ~ /- name: psaMinor$/ { if (match($0, /expression: "[0-9]+"/)) print substr($0, RSTART + 13, RLENGTH - 14) } { prev = $0 }' "$1")"
  if [[ "$(echo "${values}" | grep -c .)" != 1 ]]; then
    echo "$1 must set the psaMinor variable exactly once" >&2
    exit 1
  fi
  first="$(awk '/^  variables:/ { v = 1; next } v && /- name:/ { print $NF; exit }' "$1")"
  if [[ "${first}" != "psaMinor" ]]; then
    echo "$1 must declare psaMinor as its first variable, not ${first}" >&2
    exit 1
  fi
  echo "${values}"
}

DEFAULT=""
for policy in "${POLICIES[@]}"; do
  file="${PSS}/${policy}/$(basename "${policy}").yaml"
  minor="$(default_minor "${file}")"
  if [[ -n "${DEFAULT}" && "${minor}" != "${DEFAULT}" ]]; then
    echo "${file} defaults psaMinor to ${minor}, but other policies default it to ${DEFAULT}" >&2
    exit 1
  fi
  DEFAULT="${minor}"
done

if [[ ! -d "${TESTS}/v1-${DEFAULT}" ]]; then
  echo "${TESTS}/v1-${DEFAULT} must test the policies at their psaMinor default" >&2
  exit 1
fi

for minor in "${VERSIONS[@]}"; do
  if (( minor >= DEFAULT )); then
    echo "VERSIONS must be below the psaMinor default ${DEFAULT}, got ${minor}" >&2
    exit 1
  fi
  out="${TESTS}/v1-${minor}/policies.yaml"
  echo "Generating ${out#"${ROOT}/"} ..."
  {
    echo "# Generated by .hack/update-psa-version-tests.sh with psaMinor ${minor}. Do not edit."
    for policy in "${POLICIES[@]}"; do
      echo "---"
      tr -d '\r' < "${PSS}/${policy}/$(basename "${policy}").yaml" |
        awk -v minor="${minor}" '{ if (prev ~ /- name: psaMinor$/) sub(/expression: "[0-9]+"/, "expression: \"" minor "\""); print; prev = $0 }'
    done
  } > "${out}"
done

# expected_results writes a test directory's kyverno-test.yaml for a minor version and its policy files.
expected_results() {
  local minor="$1"
  shift
  echo "Generating ${TESTS#"${ROOT}/"}/v1-${minor}/kyverno-test.yaml ..."
  (cd "${ROOT}/.hack/psa-expected-results" && go run . "${TESTS}/resources.yaml" "${minor}" "$@") |
    tr -d '\r' > "${TESTS}/v1-${minor}/kyverno-test.yaml"
}

for minor in "${VERSIONS[@]}"; do
  expected_results "${minor}" policies.yaml
done
DEFAULT_POLICIES=()
for policy in "${POLICIES[@]}"; do
  DEFAULT_POLICIES+=("../../${policy}/$(basename "${policy}").yaml")
done
expected_results "${DEFAULT}" "${DEFAULT_POLICIES[@]}"
