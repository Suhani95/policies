const psaModule = "k8s.io/pod-security-admission"

// psaLibraryMinor returns the Kubernetes minor version of the linked PSA library.
func psaLibraryMinor() (int, error) {
	info, ok := debug.ReadBuildInfo()
	if !ok {
		return 0, fmt.Errorf("no build info")
	}
	for _, d := range info.Deps {
		if d.Path != psaModule {
			continue
		}
		if d.Replace != nil {
			d = d.Replace
		}
		parts := strings.Split(strings.TrimPrefix(d.Version, "v"), ".")
		if len(parts) < 2 {
			break
		}
		return strconv.Atoi(parts[1])
	}
	return 0, fmt.Errorf("no %s version in build info", psaModule)
}

func parseMinor(version string) (int, error) {
	m := regexp.MustCompile(`^v?1\.(\d+)$`).FindStringSubmatch(version)
	if m == nil {
		return 0, fmt.Errorf("version %q, want 1.x", version)
	}
	return strconv.Atoi(m[1])
}

// readPods reads every Pod in a multi-document YAML file.
func readPods(path string) ([]*corev1.Pod, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var pods []*corev1.Pod
	seen := map[string]bool{}
	for _, doc := range docSeparator.Split(string(data), -1) {
		var probe map[string]any
		if err := yaml.Unmarshal([]byte(doc), &probe); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if probe == nil {
			continue
		}
		if probe["kind"] != "Pod" {
			return nil, fmt.Errorf("%s: %v is not a Pod", path, probe["kind"])
		}
		// Some test fixtures have unknown fields on purpose, so don't decode strictly.
		var pod corev1.Pod
		if err := yaml.Unmarshal([]byte(doc), &pod); err != nil {
			return nil, fmt.Errorf("%s: %w", path, err)
		}
		if seen[pod.Name] {
			return nil, fmt.Errorf("%s: duplicate Pod %s", path, pod.Name)
		}
		seen[pod.Name] = true
		pods = append(pods, &pod)
	}
	sort.Slice(pods, func(i, j int) bool { return pods[i].Name < pods[j].Name })
	return pods, nil
}

// expectedTest writes a kyverno test file whose results come from upstream PSA at the given minor version.
func expectedTest(cfg *Config, set string, minor int, resources string, policyFiles []string, pods []*corev1.Pod) (string, error) {
	lib, err := psaLibraryMinor()
	if err != nil {
		return "", err
	}
	if minor > lib {
		return "", fmt.Errorf("the chart implements PSA v1.%d, but %s is v0.%d: update .hack/pss-sync/go.mod", minor, psaModule, lib)
	}
	byID := map[policy.CheckID]policy.Check{}
	for _, c := range policy.DefaultChecks() {
		byID[c.ID] = c
	}
	skip := map[string]bool{}
	for _, d := range cfg.KnownDifferences {
		if d.In == "" || d.In == set {
			skip[d.Policy+"/"+d.Pod] = true
		}
	}
	want := api.MajorMinorVersion(1, minor)
	var b strings.Builder
	b.WriteString("# Generated by .hack/pss-sync. Results come from k8s.io/pod-security-admission.\n")
	fmt.Fprintf(&b, "apiVersion: cli.kyverno.io/v1alpha1\nkind: Test\nmetadata:\n  name: pss-sync-psa-v1-%d\npolicies:\n", minor)
	for _, p := range policyFiles {
		fmt.Fprintf(&b, "- %s\n", p)
	}
	fmt.Fprintf(&b, "resources:\n- %s\nresults:\n", resources)
	var names []string
	for p := range cfg.Checks {
		names = append(names, p)
	}
	sort.Strings(names)
	for _, p := range names {
		c, ok := byID[policy.CheckID(cfg.Checks[p])]
		if !ok {
			return "", fmt.Errorf("config.yaml maps %s to unknown PSA check %s", p, cfg.Checks[p])
		}
		// A check that doesn't exist yet at this version passes every Pod.
		var fn policy.CheckPodFn
		for _, v := range c.Versions {
			if !want.Older(v.MinimumVersion) {
				fn = v.CheckPod
			}
		}
		for _, result := range []string{"fail", "pass"} {
			var rs []string
			for _, pod := range pods {
				if skip[p+"/"+pod.Name] {
					continue
				}
				allowed := fn == nil || fn(&pod.ObjectMeta, &pod.Spec).Allowed
				if (result == "pass") == allowed {
					rs = append(rs, pod.Name)
				}
			}
			if len(rs) == 0 {
				continue
			}
			fmt.Fprintf(&b, "- isValidatingPolicy: true\n  kind: Pod\n  policy: %s\n  resources:\n", p)
			for _, n := range rs {
				fmt.Fprintf(&b, "  - %s\n", n)
			}
			fmt.Fprintf(&b, "  result: %s\n", result)
		}
	}
	return b.String(), nil
}

var nonName = regexp.MustCompile(`[^a-z0-9]+`)

// boundaryPods writes one Pod for each value of each list rule, plus one value outside the list.
func boundaryPods(rules []ListRule, values map[string][]string) string {
	var b strings.Builder
	for _, rule := range rules {
		vals := append(append([]string{}, values[rule.Policy]...), rule.Probe.Outside)
		seen := map[string]bool{}
		for _, v := range vals {
			name := "pss-sync-" + strings.ToLower(rule.Probe.Field) + "-" + strings.Trim(nonName.ReplaceAllString(strings.ToLower(v), "-"), "-")
			if seen[name] {
				continue
			}
			seen[name] = true
			b.WriteString("---\napiVersion: v1\nkind: Pod\nmetadata:\n  name: " + name + "\nspec:\n")
			switch rule.Probe.Field {
			case "sysctl":
				fmt.Fprintf(&b, "  securityContext:\n    sysctls:\n    - name: %q\n      value: \"0\"\n", v)
			}
			b.WriteString("  containers:\n  - name: c\n    image: nginx\n")
			switch rule.Probe.Field {
			case "seLinuxType":
				fmt.Fprintf(&b, "    securityContext:\n      seLinuxOptions:\n        type: %q\n", v)
			case "capability":
				fmt.Fprintf(&b, "    securityContext:\n      capabilities:\n        add:\n        - %q\n", v)
			}
		}
	}
	return b.String()
}
